#[test]
fn programmes_preserve_subject_order_and_own_programme_guards() {
    for &(raw, clean, reply, programme, documentary) in CASES {
        let mut reading = Reading::new(raw);
        if let Some(clean) = clean {
            reading.line.clean = clean.to_owned();
        }
        assert_eq!(
            show_about(&reading).as_deref(),
            Some(reply),
            "{raw:?} {clean:?}"
        );
        assert_eq!(
            programme_is_wanted(&reading),
            programme,
            "{raw:?} {clean:?}"
        );
        assert_eq!(
            documentary_is_wanted(&reading),
            documentary,
            "{raw:?} {clean:?}"
        );
    }
}
