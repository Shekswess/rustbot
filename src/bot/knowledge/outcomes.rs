pub(crate) fn only_followup_words(current: &str, previous: &str) -> bool {
    use crate::bot::understanding::normalize::tokens;
    let words = tokens(current);
    let earlier = tokens(previous);
    !words.is_empty()
        && words.iter().all(|w| {
            earlier.contains(w)
                || FOLLOWUP_WORDS.binary_search(&w.as_str()).is_ok()
                || w.bytes().all(|b| b.is_ascii_digit())
        })
}
