//! Follow-up outcome questions from bot/memory/narrow.py and bot/modules/answers.py.
pub(crate) type Outcomes = &'static [(&'static str, &'static str)];
use regex::Regex;
use std::sync::LazyLock;
static SHAPES: LazyLock<Vec<(&str, Regex)>> = LazyLock::new(|| {
    vec![
    ("survives", Regex::new(r#"(?i)\bwill (?:it|that|this|they) (?:be )?(?:alright|all right|ok|okay|fine|safe)\b|\bis (?:it|that|this) (?:going to be )?(?:alright|all right|ok|okay|fine|safe)\b|\bwill (?:it|that|this) (?:survive|recover|work again|be ruined|be knackered)\b|\bis (?:it|that|this) (?:ruined|knackered|a write[- ]off|done for)\b|\bcan (?:it|that|this) be (?:saved|fixed|repaired|salvaged)\b|\bis (?:it|that|this) worth (?:fixing|repairing)\b"#).unwrap()),
    ("serious", Regex::new(r#"(?i)\bis (?:that|this|it) (?:bad|serious|dangerous|normal|common)\b|\bhow (?:bad|serious) is (?:it|that|this)\b|\bshould i (?:be )?worr(?:y|ied)\b|\bis (?:that|this) (?:something|anything) to worry about\b|\bis that (?:a|normal)\b"#).unwrap()),
    ("next", Regex::new(r#"(?i)\bwhat happens (?:now|next)\b|\bwhat next\b|\bwhat(?:'s| is| was) (?:the )?next\b|\bso what now\b|\bwhat now\b"#).unwrap()),
    ("explain", Regex::new(r#"(?i)\bwhat does (?:that|this|it) mean\b|\bwhat do you mean\b|\bwhat(?:'s| is) that (?:mean|mean then)\b|\bmeaning what\b"#).unwrap()),
]
});

/// Select an outcome only when the current ask is about the active card.
pub(crate) fn owed(outcomes: Outcomes, line: &str, same_subject: bool) -> Option<&'static str> {
    if !same_subject || outcomes.is_empty() {
        return None;
    }
    for (shape, pattern) in SHAPES.iter() {
        if !pattern.is_match(line) {
            continue;
        }
        return outcomes.iter().find_map(|&(name, sentence)| {
            (name == *shape && !sentence.trim().is_empty()).then_some(sentence)
        });
    }
    None
}

