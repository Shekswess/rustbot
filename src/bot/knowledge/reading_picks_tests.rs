#[test]
fn reading_callbacks_preserve_subject_context_age_and_reservation_guards() {
    for &(
        raw,
        history,
        (subject, subject_guard),
        (recommendation, recommendation_guard),
        (comic, comic_guard),
    ) in CASES
    {
        let reading = Reading::new(raw);
        let earlier = history
            .iter()
            .map(|&user| Exchange {
                user: user.to_owned(),
                bot: String::new(),
                module: "greeting",
            })
            .collect::<Vec<_>>();
        assert_eq!(
            about_subject(&reading).as_deref(),
            subject.map(|index| REPLIES[index]),
            "subject: {raw:?} {history:?}"
        );
        assert_eq!(
            subject_is_wanted(&reading),
            subject_guard,
            "subject guard: {raw:?} {history:?}"
        );
        assert_eq!(
            recommend(&reading, &earlier).as_deref(),
            recommendation.map(|index| REPLIES[index]),
            "recommend: {raw:?} {history:?}"
        );
        assert_eq!(
            recommendation_is_wanted(&reading),
            recommendation_guard,
            "recommend guard: {raw:?} {history:?}"
        );
        assert_eq!(
            comics(&reading, &earlier).as_deref(),
            Some(REPLIES[comic]),
            "comic: {raw:?} {history:?}"
        );
        assert_eq!(
            comic_pick_is_wanted(&reading),
            comic_guard,
            "comic guard: {raw:?} {history:?}"
        );
    }
}
