pub(crate) fn claim_applies(text: &str) -> bool {
    let mut said = String::from(" ");
    said.push_str(&text.to_lowercase());
    let names_one = |options: &[&str]| {
        options.iter().any(|part| {
            said.match_indices(part)
                .any(|(at, _)| at > 0 && said.as_bytes()[at - 1] == b' ')
        })
    };
    !A_WINDOW_ON_A_CAR.is_match(&said) || names_one(SOMEBODY_DID_IT) || !names_one(A_FAULT)
}
