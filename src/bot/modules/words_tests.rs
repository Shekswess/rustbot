#[test]
fn the_question_must_ask_for_the_last_answers_actual_quoted_sentence() {
    for &(line, prior, index, claim) in CASES {
        let memory = Memory {
            turns: prior
                .iter()
                .map(|&index| {
                    let (user, bot, module) = TURNS[index];
                    Exchange {
                        user: user.to_owned(),
                        bot: bot.to_owned(),
                        module,
                    }
                })
                .collect(),
            ..Memory::default()
        };
        let actual = respond(&Reading::new(line), &memory);
        assert_eq!(
            actual.as_deref(),
            index.map(|index| REPLIES[index]),
            "{line} {prior:?}"
        );
        assert_eq!(actual.is_some(), claim, "{line} {prior:?}");
    }
}
