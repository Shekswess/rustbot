#[test]
fn pace_keeps_the_source_steps_duration_topic_and_claim_fences() {
    let mut differences = Vec::new();
    for &(line, previous, reply, claims) in CASES {
        let reading = Reading::new(line);
        let memory = Memory {
            turns: previous
                .iter()
                .map(|&index| {
                    let (user, bot, module) = TURNS[index];
                    Exchange {
                        user: user.to_owned(),
                        bot: bot.to_owned(),
                        module,
                    }
                })
                .collect(),
            ..Memory::default()
        };
        let actual = respond(&reading, &memory);
        let expected = reply.map(|index| REPLIES[index]);
        if actual.as_deref() != expected || actual.is_some() != claims {
            differences.push((line, previous, expected, actual, claims));
        }
    }
    assert!(differences.is_empty(), "{differences:#?}");
}
