#[test]
fn matches_source_choice_after_previous_pool_replies() {
    let replies = answers();
    let cases: &[(&str, &[usize], usize)] = &[
        ("do you fancy a pint", &[0], 1),
        ("do you fancy a pint", &[1], 0),
        ("do you fancy a pint", &[0, 1], 0),
        ("do you fancy a pint", &[1, 0], 1),
        ("do you fancy a pint", &[0, 1, 0, 1], 0),
        ("do you fancy a pint", &[0, 8, 0], 1),
        ("would you fancy a meal", &[2], 3),
        ("would you fancy a meal", &[3], 2),
        ("would you fancy a meal", &[2, 3], 2),
        ("would you fancy a meal", &[3, 2], 3),
        ("would you fancy a meal", &[2, 3, 2, 3], 2),
        ("would you fancy a meal", &[0, 8, 2], 3),
        ("do you fancy a walk", &[4], 5),
        ("do you fancy a walk", &[5], 4),
        ("do you fancy a walk", &[4, 5], 4),
        ("do you fancy a walk", &[5, 4], 5),
        ("do you fancy a walk", &[4, 5, 4, 5], 4),
        ("do you fancy a walk", &[0, 8, 4], 5),
        ("shall we go to the cinema", &[6], 7),
        ("shall we go to the cinema", &[7], 6),
        ("shall we go to the cinema", &[6, 7], 6),
        ("shall we go to the cinema", &[7, 6], 7),
        ("shall we go to the cinema", &[6, 7, 6, 7], 6),
        ("shall we go to the cinema", &[0, 8, 6], 7),
        ("fancy the shops", &[8], 9),
        ("fancy the shops", &[9], 8),
        ("fancy the shops", &[8, 9], 8),
        ("fancy the shops", &[9, 8], 9),
        ("fancy the shops", &[8, 9, 8, 9], 8),
        ("fancy the shops", &[0, 8, 8], 9),
        ("want to go to the beach", &[10], 11),
        ("want to go to the beach", &[11], 10),
        ("want to go to the beach", &[10, 11], 10),
        ("want to go to the beach", &[11, 10], 11),
        ("want to go to the beach", &[10, 11, 10, 11], 10),
        ("want to go to the beach", &[0, 8, 10], 11),
        ("are you coming to my party", &[12], 13),
        ("are you coming to my party", &[13], 12),
        ("are you coming to my party", &[12, 13], 12),
        ("are you coming to my party", &[13, 12], 13),
        ("are you coming to my party", &[12, 13, 12, 13], 12),
        ("are you coming to my party", &[0, 8, 12], 13),
        ("can you come round", &[14], 15),
        ("can you come round", &[15, 16], 14),
        ("can you come round", &[14, 15, 16], 14),
        ("can you come round", &[16, 15, 14], 16),
        ("can you come round", &[14, 15, 16, 14, 15, 16], 14),
        ("can you come round", &[0, 8, 14], 15),
    ];
    for &(line, past, expected) in cases {
        let turns = past
            .iter()
            .map(|&at| Exchange {
                user: "earlier invitation".into(),
                bot: replies[at].into(),
                module: "invitation",
            })
            .collect();
        let memory = Memory {
            turns,
            ..Memory::default()
        };
        assert_eq!(
            respond(&Reading::new(line), &memory).as_deref(),
            Some(replies[expected]),
            "{line:?} {past:?}"
        );
    }
}
